console.log('LOOPING FOR PERTAMA');
for (let i = 1; i <= 20; i++) {
  console.log(`${i} - I love coding`);
}

console.log('LOOPING FOR KEDUA');
for (let i = 20; i >= 1; i--) {
  console.log(`${i} - I will become fullstack developer`);
}

console.log('LOOPING WHILE PERTAMA');

let i = 2;
while (i <= 20) {
  console.log(`${i} - I love coding`);
  i += 2;
}

console.log('LOOPING WHILE KEDUA');

i = 20;
while (i >= 2) {
  console.log(`${i} - I love coding`);
  i -= 2;
}